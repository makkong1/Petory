-- 거래 확정 시 "그때 동의한 금액"을 함께 기록한다.
--
-- V14 를 정정하는 마이그레이션이다.
--
-- V14 에서는 carerequest.offered_coins_updated_at(금액 변경 시각)과 참여자의 deal_confirmed_at
-- (확정 시각)을 비교해 낡은 동의를 가려내려 했다. 시나리오는 이렇다.
--     제공자: 5,000 보고 확정
--     요청자: 금액을 1,000 으로 수정
--     요청자: 1,000 보고 확정  -> 계약 성립. 그런데 제공자의 동의는 5,000 에 대한 것이었다
--
-- 그런데 두 컬럼 모두 `datetime`(초 단위)이라, 확정과 금액 변경이 같은 초 안에 일어나면
-- 두 시각이 같아져 isBefore 비교가 false 가 된다. 테스트에서 실제로 그렇게 통과해버렸다
-- (CareDealAmountAgreementTest 의 "금액 변경시 옛 확정 무효화"가 처음에 실패한 이유).
-- datetime(6) 으로 정밀도를 올려 막을 수도 있지만, 그건 "시계가 충분히 촘촘하면 맞는" 방식이다.
--
-- 그래서 시각 비교를 버리고 **동의한 금액 자체를 기록**한다. 불변식을 직접 표현한다.
--     "성립한 계약의 모든 동의는 현재 금액과 같은 금액에 대한 것이다"
-- 확정 시 현재 금액과 다른 동의가 있으면 무효화하고 다시 받는다. 시계와 무관하게 성립한다.
--
-- carerequest.offered_coins_updated_at 은 남긴다 — 판정 근거로는 더 쓰지 않지만
-- "금액이 언제 바뀌었는지"는 화면에 보여줄 수 있는 정보다.

ALTER TABLE `conversationparticipant`
    ADD COLUMN `confirmed_offered_coins` int DEFAULT NULL
        COMMENT '거래 확정 시 동의한 제시 금액 (NULL = 미확정). 현재 금액과 다르면 낡은 동의다';
