-- 제안에 "그때 제시된 금액"을 함께 기록한다.
--
-- 케어 계약을 대칭 확정(양쪽이 같은 버튼을 각자 누름)에서 제안/수락으로 바꾸면서 필요해졌다.
--
-- 대칭 확정에서는 두 동의가 서로 다른 금액에 대한 것일 수 있어서, 확정할 때마다 기존 동의를
-- 현재 금액과 대조해 무효화해야 했다(V15 참고 — 그 불변식을 채팅 참여자 행에 들고 있었다).
-- 제안/수락은 동의가 한 번뿐이다. 요청자가 제안을 보내는 순간의 금액을 제안이 들고 있고,
-- 제공자는 그 금액을 보고 수락한다. "성립한 계약의 모든 동의는 같은 금액에 대한 것"이
-- 무효화 로직 없이 성립한다.
--
-- 대조는 수락 시점에 한 번 한다 — 제안을 보낸 뒤 요청자가 금액을 바꿀 수 있기 때문이다.
-- 그때는 수락을 거절하고 요청자가 새 금액으로 다시 제안한다.
--
-- 기존 행(V18 이전에 만들어진 지원)은 NULL 로 남는다. 그 지원들은 제안 경로를 거치지 않았고
-- 금액 대조 대상도 아니다 — NULL 이면 대조를 건너뛴다.

ALTER TABLE `careapplication`
    ADD COLUMN `offered_coins` int DEFAULT NULL
        COMMENT '제안 시점의 제시 금액 (NULL = 제안 경로를 거치지 않은 옛 지원)';
